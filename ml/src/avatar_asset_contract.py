"""Integrity and export-contract validation for original avatar candidates.

The validator deliberately uses only the Python standard library so candidate
assets can be audited without Blender. It validates generated files; it does
not approve a candidate for publication or copy it into the mobile bundle.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import struct
from typing import Any, Mapping


GLB_JSON_CHUNK = 0x4E4F534A
PNG_SIGNATURE = b"\x89PNG\r\n\x1a\n"
EXPECTED_OUTPUTS = {
    "blend",
    "glb",
    "motionContactSheet",
    "motionAuditReport",
    "motionPreviewMp4",
    "poseSheet1280x720",
    "poseSheet360x640",
}
EXPECTED_AVATAR_ID = "naira-v2"
EXPECTED_BUILDER_VERSION = "2.0.0"
APPROVED_CONCEPT_SHA256 = "d1b8a0f71751ab9b96ca8c150c0789b66712e14b624efcbe6babd5a42d64f456"
GEOMETRY_METHOD = "Deterministic procedural Blender primitives generated by the builder"
REQUIRED_DEFORM_BONES = frozenset(
    {
        "DEF-spine.006",
        "DEF-upper_arm.L",
        "DEF-upper_arm.R",
        "DEF-forearm.L",
        "DEF-forearm.R",
        "DEF-hand.L",
        "DEF-hand.R",
        "DEF-thumb.01.L",
        "DEF-thumb.01.R",
        "DEF-f_index.03.L",
        "DEF-f_index.03.R",
        "DEF-eye.L",
        "DEF-eye.R",
        "DEF-jaw",
        "DEF-cheek.B.L",
        "DEF-cheek.B.R",
        "DEF-lid.B.L",
        "DEF-lid.B.R",
        "DEF-lid.T.L",
        "DEF-lid.T.R",
        "DEF-lip.T.L.001",
        "DEF-lip.T.R.001",
    }
)
FORBIDDEN_LOWER_BODY_PREFIXES = ("DEF-thigh.", "DEF-shin.", "DEF-foot.", "DEF-toe.")


class AvatarAssetContractError(ValueError):
    """Raised when a generated candidate violates the asset contract."""


def _require(condition: bool, message: str) -> None:
    if not condition:
        raise AvatarAssetContractError(message)


def sha256_file(path: Path) -> str:
    """Return a streaming SHA-256 digest for *path*."""
    digest = hashlib.sha256()
    with path.open("rb") as source:
        for chunk in iter(lambda: source.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def png_dimensions(path: Path) -> tuple[int, int]:
    """Read PNG dimensions without decoding the image."""
    with path.open("rb") as source:
        header = source.read(24)
    _require(len(header) == 24 and header[:8] == PNG_SIGNATURE, f"{path.name} is not a PNG")
    return struct.unpack(">II", header[16:24])


def is_mp4(path: Path) -> bool:
    """Return whether *path* starts with an ISO BMFF file-type box."""
    payload = path.read_bytes()[:32]
    return len(payload) >= 12 and payload[4:8] == b"ftyp"


def read_glb_json(path: Path) -> Mapping[str, Any]:
    """Parse the JSON chunk and structural header of a GLB 2.0 file."""
    payload = path.read_bytes()
    _require(len(payload) >= 20, "GLB is too short")
    magic, version, declared_length = struct.unpack_from("<4sII", payload, 0)
    _require(magic == b"glTF", "GLB magic is invalid")
    _require(version == 2, f"GLB version must be 2, found {version}")
    _require(declared_length == len(payload), "GLB declared length does not match file size")
    offset = 12
    document: Mapping[str, Any] | None = None
    while offset < len(payload):
        _require(offset + 8 <= len(payload), "GLB chunk header is truncated")
        chunk_length, chunk_type = struct.unpack_from("<II", payload, offset)
        offset += 8
        _require(offset + chunk_length <= len(payload), "GLB chunk is truncated")
        chunk = payload[offset : offset + chunk_length]
        offset += chunk_length
        if chunk_type == GLB_JSON_CHUNK:
            _require(document is None, "GLB contains more than one JSON chunk")
            parsed = json.loads(chunk.rstrip(b" \x00").decode("utf-8"))
            _require(isinstance(parsed, dict), "GLB JSON root must be an object")
            document = parsed
    _require(offset == len(payload), "GLB contains trailing bytes")
    _require(document is not None, "GLB has no JSON chunk")
    assert document is not None
    return document


def _safe_output_path(candidate_directory: Path, relative_path: object) -> Path:
    _require(isinstance(relative_path, str) and bool(relative_path), "Output path must be a string")
    if not isinstance(relative_path, str):
        raise AvatarAssetContractError("Output path must be a string")
    path = Path(relative_path)
    _require(not path.is_absolute() and len(path.parts) == 1, "Output paths must be local filenames")
    resolved = (candidate_directory / path).resolve()
    _require(resolved.parent == candidate_directory.resolve(), "Output escapes candidate directory")
    _require(resolved.is_file() and not resolved.is_symlink(), f"Missing regular output {path}")
    return resolved


def validate_avatar_candidate(manifest_path: Path) -> dict[str, Any]:
    """Validate one generated Naira candidate and return its manifest."""
    manifest_path = manifest_path.resolve()
    document = json.loads(manifest_path.read_text(encoding="utf-8"))
    _require(isinstance(document, dict), "Manifest root must be an object")
    _require(document.get("schema") == "vozual.avatar-candidate", "Unexpected manifest schema")
    _require(document.get("schemaVersion") == 1, "Unsupported manifest schema version")
    _require(document.get("avatarId") == EXPECTED_AVATAR_ID, "Unexpected avatar identifier")
    _require(document.get("builderVersion") == EXPECTED_BUILDER_VERSION, "Unexpected builder version")

    character = document.get("character")
    _require(isinstance(character, dict), "Character metadata is required")
    _require(character.get("name") == "Naira", "Character name must be Naira")
    for flag in ("adult", "fictional", "originalProceduralGeometry"):
        _require(character.get(flag) is True, f"Character {flag} must be true")
    _require(character.get("usesThirdPartyMeshOrTexture") is False, "Third-party mesh or texture is forbidden")

    status = document.get("status")
    _require(isinstance(status, dict), "Candidate status is required")
    _require(status.get("productionReady") is False, "Task 2 candidate must not be production-ready")
    _require(status.get("technicalApproval") == "candidate", "Technical status must remain candidate")

    provenance = document.get("provenance")
    _require(isinstance(provenance, dict), "Provenance metadata is required")
    _require(provenance.get("builder") == "ml/src/blender_build_original_avatar.py", "Unexpected builder")
    _require(provenance.get("conceptUsedAsGeometryOrTexture") is False, "Concept imagery cannot become geometry or texture")
    _require(provenance.get("conceptSha256") == APPROVED_CONCEPT_SHA256, "Approved concept checksum is required")
    _require(bool(provenance.get("conceptPath")), "Approved concept path is required")
    _require(provenance.get("geometryMethod") == GEOMETRY_METHOD, "Procedural geometry method is required")

    licence = document.get("licence")
    _require(isinstance(licence, dict) and licence.get("publicationReviewRequired") is True, "Licence review gate is required")
    _require(bool(licence.get("asset")) and bool(licence.get("rigify")), "Asset and Rigify licence records are required")

    exports = document.get("outputs")
    _require(isinstance(exports, dict) and set(exports) == EXPECTED_OUTPUTS, "Output set is incomplete or unexpected")
    candidate_directory = manifest_path.parent
    if "mobile" in candidate_directory.parts and "assets" in candidate_directory.parts:
        raise AvatarAssetContractError("Unapproved candidate cannot be generated inside packaged mobile assets")
    output_paths: dict[str, Path] = {}
    for name, metadata in exports.items():
        _require(isinstance(metadata, dict), f"Output metadata for {name} must be an object")
        path = _safe_output_path(candidate_directory, metadata.get("path"))
        _require(metadata.get("bytes") == path.stat().st_size, f"Byte size mismatch for {name}")
        _require(metadata.get("sha256") == sha256_file(path), f"SHA-256 mismatch for {name}")
        output_paths[name] = path

    _require(png_dimensions(output_paths["poseSheet1280x720"]) == (1280, 720), "Desktop pose sheet must be 1280x720")
    _require(png_dimensions(output_paths["poseSheet360x640"]) == (360, 640), "Mobile pose sheet must be 360x640")
    _require(png_dimensions(output_paths["motionContactSheet"]) == (720, 1280), "Motion contact sheet must be 720x1280")
    _require(is_mp4(output_paths["motionPreviewMp4"]), "Motion preview must be an MP4")

    scope = document.get("scope")
    _require(isinstance(scope, dict) and scope.get("upperBodyOnly") is True, "Candidate must be upper-body only")
    _require(scope.get("visibleRegions") == ["head", "neck", "torso", "arms", "wrists", "hands"], "Unexpected visible geometry regions")
    motion = document.get("motionEvidence")
    _require(isinstance(motion, dict) and motion.get("notAnLscSign") is True, "Motion evidence must not claim an LSC sign")
    _require(motion.get("durationSeconds") == 10 and motion.get("fps") == 30, "Unexpected motion-preview timing")
    _require(motion.get("internalAuditSampleFps") == 60, "Motion preview must be audited at 60 FPS")
    audit = json.loads(output_paths["motionAuditReport"].read_text(encoding="utf-8"))
    _require(audit.get("passed") is True, "Motion smoothness audit did not pass")
    _require(audit.get("sampleFps") == 60 and audit.get("renderFps") == 30, "Motion audit sampling is invalid")
    _require(audit.get("quaternionHemisphereContinuity") is True, "Quaternion flip detected")
    _require(audit.get("loopSeamPassed") is True and audit.get("neutralHoldStable") is True, "Idle loop is not seamless and stable")

    glb = read_glb_json(output_paths["glb"])
    _require(glb.get("asset", {}).get("version") == "2.0", "Export must identify glTF 2.0")
    _require(len(glb.get("meshes", [])) <= document["budgets"]["meshTargetMaximum"], "GLB exceeds mesh budget")
    _require(len(glb.get("images", [])) == 0, "Procedural candidate must not embed image textures")
    _require(len(glb.get("animations", [])) == 0, "Task 2 neutral candidate must not embed animations")
    nodes = glb.get("nodes", [])
    skins = glb.get("skins", [])
    _require(isinstance(nodes, list) and isinstance(skins, list) and len(skins) == 1, "GLB must have exactly one skin")
    joint_names = {
        nodes[index].get("name")
        for index in skins[0].get("joints", [])
        if isinstance(index, int) and 0 <= index < len(nodes) and isinstance(nodes[index], dict)
    }
    forbidden_joints = sorted(
        name
        for name in joint_names
        if isinstance(name, str) and name.startswith(FORBIDDEN_LOWER_BODY_PREFIXES)
    )
    _require(not forbidden_joints, f"GLB contains forbidden lower-body joints: {', '.join(forbidden_joints)}")
    required_bones = document.get("rig", {}).get("requiredDeformBones", [])
    _require(isinstance(required_bones, list) and bool(required_bones), "Required deform bones are missing")
    undeclared_contract_bones = sorted(REQUIRED_DEFORM_BONES - set(required_bones))
    _require(
        not undeclared_contract_bones,
        f"Manifest omits contract deform bones: {', '.join(undeclared_contract_bones)}",
    )
    missing = sorted(set(required_bones) - joint_names)
    _require(not missing, f"GLB skin is missing required deform bones: {', '.join(missing)}")
    _require(output_paths["glb"].stat().st_size <= document["budgets"]["glbMaximumBytes"], "GLB exceeds byte budget")
    _require(document["rig"]["deformBoneCount"] <= document["budgets"]["deformBoneMaximum"], "Rig exceeds deform-bone budget")
    return document


def main() -> None:
    parser = argparse.ArgumentParser(description="Verify a generated original-avatar candidate")
    parser.add_argument("manifest", type=Path)
    arguments = parser.parse_args()
    manifest = validate_avatar_candidate(arguments.manifest)
    print(f"Validated {manifest['avatarId']} candidate: {arguments.manifest.resolve()}")


if __name__ == "__main__":
    main()
